/**
 * Works out which Supabase tables each query module reads, so a page loads
 * only those tables instead of all of them.
 *
 *   npm run db:needs        (also runs automatically before `npm run build`)
 *
 * Writes lib/data/queries/needs.ts, then checks every page: its
 * `loadDb(needsFor(...))` call must list every query module the page (or a
 * server component next to it) imports. A missing module fails the build.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const ROOT = join(__dirname, "..");
const QUERIES = join(ROOT, "lib/data/queries");
const read = (p: string) => readFileSync(p, "utf8");

/* ---------------------------------------------- tables per query module */

const modules = readdirSync(QUERIES)
  .filter((f) => f.endsWith(".ts") && f !== "needs.ts")
  .map((f) => f.replace(/\.ts$/, ""));

const direct: Record<string, Set<string>> = {};
const deps: Record<string, string[]> = {};
for (const m of modules) {
  const src = read(join(QUERIES, `${m}.ts`));
  direct[m] = new Set([...src.matchAll(/db\(\)\.([A-Za-z]+)/g)].map((x) => x[1]));
  deps[m] = [...src.matchAll(/^import (?!type)[^;]*from "\.\/([a-z-]+)";/gm)].map((x) => x[1]);
}

function closure(m: string, seen = new Set<string>()): Set<string> {
  if (seen.has(m)) return new Set();
  seen.add(m);
  const out = new Set(direct[m]);
  for (const d of deps[m] ?? []) for (const t of closure(d, seen)) out.add(t);
  return out;
}

// `users` is always loaded (names and avatars everywhere; account check).
const needs = Object.fromEntries(modules.map((m) => [m, [...closure(m)].filter((t) => t !== "users").sort()]));

const body = `// Generated by scripts/generate-query-needs.ts – do not edit.
import type { TableKey } from "../tables";

export const NEEDS = ${JSON.stringify(needs, null, 2)} as const satisfies Record<string, readonly TableKey[]>;

export type QueryModule = keyof typeof NEEDS;

/** Tables a page needs, given the query modules it uses. */
export function needsFor(...mods: QueryModule[]): TableKey[] {
  return [...new Set(mods.flatMap((m) => NEEDS[m] as readonly TableKey[]))];
}
`;
writeFileSync(join(QUERIES, "needs.ts"), body);
console.log(`wrote lib/data/queries/needs.ts (${modules.length} modules)`);

/* ------------------------------------------------------ check every page */

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const queryImports = (src: string) =>
  [...src.matchAll(/^import (?!type)[^;]*from "@\/lib\/data\/queries\/([a-z-]+)";/gm)].map((x) => x[1]).filter((m) => m !== "needs");

const problems: string[] = [];
for (const page of walk(join(ROOT, "app")).filter((p) => /[\\/]page\.tsx$/.test(p))) {
  const src = read(page);
  const used = new Set(queryImports(src));
  // Server components imported from the same folder render in the same request.
  for (const m of src.matchAll(/^import [^;]*from "(\.\/[^"]+)";/gm)) {
    const file = resolve(dirname(page), m[1]) + ".tsx";
    try {
      const child = read(file);
      if (!/^["']use client["']/.test(child.trimStart())) for (const q of queryImports(child)) used.add(q);
    } catch {
      /* not a .tsx component */
    }
  }
  if (used.size === 0) continue;
  const call = src.match(/loadDb\(needsFor\(([^)]*)\)\)/);
  const listed = new Set(call ? [...call[1].matchAll(/"([a-z-]+)"/g)].map((x) => x[1]) : []);
  const missing = [...used].filter((m) => !listed.has(m));
  if (!call || missing.length) {
    problems.push(`${relative(ROOT, page)}: loadDb(needsFor(...)) must include ${missing.map((m) => `"${m}"`).join(", ") || "its query modules"}`);
  }
}

if (problems.length) {
  console.error("Pages missing table needs:\n  " + problems.join("\n  "));
  process.exit(1);
}
console.log("all pages declare their table needs");
